// Generates src/lib/api/schema.d.ts from openapi/api.v1.json.
// Some backend endpoints (Tenancy) read `{workspaceId}` from the route without binding it, so ASP.NET leaves it out of the
// document. Every `{name}` in a path template is declared here as a required string path parameter when missing,
// so the typed client can substitute it. Remove this once the backend document declares them itself.
import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const source = JSON.parse(await readFile(new URL("../openapi/api.v1.json", import.meta.url), "utf8"));
const methods = ["get", "put", "post", "delete", "patch", "head", "options"];
let patched = 0;

for (const [path, item] of Object.entries(source.paths ?? {})) {
  const names = [...path.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]);
  for (const method of methods) {
    const op = item[method];
    if (!op) continue;
    op.parameters ??= [];
    for (const name of names) {
      const declared = [...op.parameters, ...(item.parameters ?? [])].some((p) => p.in === "path" && p.name === name);
      if (!declared) {
        op.parameters.push({ name, in: "path", required: true, schema: { type: "string" } });
        patched++;
      }
    }
  }
}

const ast = await openapiTS(source);
const header = "/**\n * This file was auto-generated by scripts/gen-api.mjs (openapi-typescript).\n * Do not make direct changes to the file.\n */\n\n";
await writeFile(new URL("../src/lib/api/schema.d.ts", import.meta.url), header + astToString(ast));
console.log(`schema.d.ts written (${patched} undeclared path parameters added)`);
