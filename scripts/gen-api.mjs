// Generates src/lib/api/schema.d.ts from openapi/api.v1.json (copied from the backend's backend/openapi/api.v1.json).
import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const source = JSON.parse(await readFile(new URL("../openapi/api.v1.json", import.meta.url), "utf8"));
const ast = await openapiTS(source);
const header = "/**\n * This file was auto-generated by scripts/gen-api.mjs (openapi-typescript).\n * Do not make direct changes to the file.\n */\n\n";
await writeFile(new URL("../src/lib/api/schema.d.ts", import.meta.url), header + astToString(ast));
console.log("schema.d.ts written");
